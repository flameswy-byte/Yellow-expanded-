          '\tlock',
          '\tfaceplayer',
          f'\tgoto_if_unset FLAG_SYS_POKEMON_GET, {NAME}_EventScript_SlimeTraderNoMon',
          f'\tgoto_if_set {FLAG}, {NAME}_EventScript_SlimeTraderDone',
          f'\tcall {NAME}_EventScript_SlimeTraderPick',
          '\tcopyvar VAR_0x8004, VAR_0x8008',
          '\tspecialvar VAR_RESULT, GetInGameTradeSpeciesInfo',
          '\tcopyvar VAR_0x8009, VAR_RESULT',
          f'\tmsgbox {NAME}_Text_SlimeTraderOffer, MSGBOX_YESNO',
          f'\tgoto_if_eq VAR_RESULT, NO, {NAME}_EventScript_SlimeTraderDecline',
          '\tspecial ChoosePartyMon',
          '\tcopyvar VAR_0x800A, VAR_0x8004',
          f'\tgoto_if_eq VAR_0x8004, PARTY_NOTHING_CHOSEN, {NAME}_EventScript_SlimeTraderDecline',
          '\tcopyvar VAR_0x8005, VAR_0x800A',
          '\tspecialvar VAR_RESULT, GetTradeSpecies',
          f'\tgoto_if_ne VAR_RESULT, VAR_0x8009, {NAME}_EventScript_SlimeTraderWrongMon',
          '\tcopyvar VAR_0x8004, VAR_0x8008',
          '\tcopyvar VAR_0x8005, VAR_0x800A',
          '\tspecial CreateInGameTradePokemon',
