"""Two people in Littleroot who want something you have.

The first will trade you a POKeMON for your starter and will not say what.
That is the whole point of him, so the text never names the species and the
script never buffers it - vanilla's trade dialogue puts the offered species in
STR_VAR_2, and simply not using STR_VAR_2 is what keeps the secret. The trade
scene reveals it, which is after you have agreed, which is where a mystery
belongs.

He needs three entries in sIngameTrades rather than one, because an in-game
trade asks for a fixed species and the starter is one of three. VAR_STARTER_MON
picks which.

The second is Steven, who wants LIQUID ORE - a new item, found in the deepest
corners of the new routes by tools/populate.py - and will hand over a level 1
METAL SLIME for each one. He is a man who collects rare stones and this is the
rarest thing in Hoenn, and neither of them mentions that it is the same
substance the POKeMON is made of.

The item's icon is drawn from METAL SLIME's own palette, for the same reason.

    python3 tools/trades.py            # apply
    python3 tools/trades.py --check    # verify what is written
"""
