# --- the item -------------------------------------------------------------
def metal_slime_palette():
    """the greys METAL SLIME is drawn in, lightest first.

    Its palette also carries two rust entries at 8 and 9, left over from the
    basic slime; the sprite no longer uses them and neither does this.
    """
    from PIL import Image
    im = Image.open(f'{R.ROOT}/graphics/pokemon/metal_slime/front.png')
    p = im.getpalette()[:16*3]
    cols = [tuple(p[i*3:i*3+3]) for i in range(16)]
    return [cols[i] for i in (1, 2, 4, 5, 6, 7, 10, 12, 14, 15)]


def draw_icon():
    """a 24x24 bead of the stuff, lit from the top left.

    Item icons are 24x24 and 4bpp, and the .pal beside them is what the game
    actually loads - the PNG's own palette only has to agree with it, index for
    index, or gbagfx writes the right shape in the wrong colours.
    """
    from PIL import Image
    ramp = metal_slime_palette()
    pal = [(0, 0, 0)] + ramp + [(0, 0, 0)] * (16 - 1 - len(ramp))

    W = 24
    px = [[0] * W for _ in range(W)]
    DARK = len(ramp)                # the last ramp entry, used as the outline
    BODY = len(ramp) - 2            # how many shades the body gets

    def blob(cx, cy, rx, ry, lift):
        """a lit ellipse, painted body-first so the outline can go round it."""
        inside = set()
        for y in range(W):
            for x in range(W):
                dx, dy = (x - cx) / rx, (y - cy) / ry
                if dx*dx + dy*dy <= 1.0:
                    inside.add((x, y))
        for x, y in inside:
            # distance from a light source up and left of the blob, which is
            # where every item icon in this game is lit from
            lx, ly = (x - (cx - rx*0.42)) / rx, (y - (cy - ry*0.46)) / ry
            band = min(BODY - 1, max(0, int((lx*lx + ly*ly) * BODY * 0.85)))
            px[y][x] = 1 + band + lift
        # the outline: every cell touching the blob from outside
        for x, y in list(inside):
            for nx, ny in ((x+1, y), (x-1, y), (x, y+1), (x, y-1)):
                if (0 <= nx < W and 0 <= ny < W and (nx, ny) not in inside):
                    px[ny][nx] = DARK
        return inside

    blob(11.0, 15.0, 6.8, 5.0, 0)
    # Two beads adrift above it, the way METAL SLIME is drawn - well clear of
    # the bead and of each other, and different sizes. Sitting them level and
    # symmetrical either side made the whole icon read as a face with ears.
    blob(18.0, 4.0, 2.1, 2.1, 1)
    blob(4.5, 7.0, 1.3, 1.3, 1)

    # the specular, which is what makes it read as metal rather than as a rock
    for y, x in ((12, 7), (12, 8), (11, 8), (13, 7)):
        px[y][x] = 1

    im = Image.new('P', (W, W))
    flat = []
    for c in pal:
        flat += list(c)
    im.putpalette(flat + [0] * (768 - len(flat)))
    im.putdata([px[y][x] for y in range(W) for x in range(W)])
    return im, pal


def write_icon(dry):
    im, pal = draw_icon()
    if dry:
        return
    os.makedirs(os.path.dirname(f'{R.ROOT}/{ICON}'), exist_ok=True)
    im.save(f'{R.ROOT}/{ICON}')
    # .gitattributes marks *.pal as eol=crlf, and every other palette in the
    # tree is written that way; newline='' keeps Python from undoing it
    with open(f'{R.ROOT}/{PAL}', 'w', newline='') as f:
        f.write('JASC-PAL\r\n0100\r\n16\r\n')
        for c in pal:
            f.write(f'{c[0]} {c[1]} {c[2]}\r\n')


def add_item(dry):
    """the constant, the table row, the icon, and the two declarations."""
    done = []

    p = f'{R.ROOT}/include/constants/items.h'
    text = open(p).read()
    if ITEM not in text:
        m = re.search(r'^#define ITEMS_COUNT (\d+)$', text, re.M)
        n = int(m.group(1))
        pad = ' ' * max(1, 33 - len(ITEM))
        text = text.replace(
            m.group(0),
            f'\n// Open Hoenn - tools/trades.py\n'
            f'#define {ITEM}{pad}{n}\n\n#define ITEMS_COUNT {n + 1}', 1)
        done.append(f'{ITEM} = {n}, ITEMS_COUNT {n} -> {n + 1}')
        if not dry:
            open(p, 'w').write(text)

    p = f'{R.ROOT}/src/data/text/item_descriptions.h'
    text = open(p).read()
    if 'sLiquidOreDesc' not in text:
        text = text.rstrip('\n') + (
            f'\n\n{MARK}\nstatic const u8 sLiquidOreDesc[] = _(\n'
            f'    "{ITEM_DESC}");\n')
        done.append('description')
        if not dry:
            open(p, 'w').write(text)

    p = f'{R.ROOT}/src/data/items.h'
    text = open(p).read()
    if f'[{ITEM}]' not in text:
        row = (f'    {MARK}\n'
               f'    [{ITEM}] =\n'
               f'    {{\n'
               f'        .name = _("{ITEM_NAME}"),\n'
               f'        .itemId = {ITEM},\n'
               f'        .price = 0,\n'
               f'        .description = sLiquidOreDesc,\n'
               f'        .pocket = POCKET_ITEMS,\n'
               f'        .type = ITEM_USE_BAG_MENU,\n'
               f'        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,\n'
               f'    }},\n')
        i = text.rindex('};')
        text = text[:i] + row + text[i:]
        done.append('gItems row')
        if not dry:
            open(p, 'w').write(text)

    p = f'{R.ROOT}/src/data/graphics/items.h'
    text = open(p).read()
    if 'gItemIcon_LiquidOre' not in text:
        text = text.rstrip('\n') + (
            f'\n\n{MARK}\n'
            f'const u32 gItemIcon_LiquidOre[] = INCGFX_U32("{ICON}", ".4bpp.lz");\n'
            f'const u32 gItemIconPalette_LiquidOre[] = '
            f'INCGFX_U32("{PAL}", ".gbapal.lz");\n')
        done.append('graphics')
        if not dry:
            open(p, 'w').write(text)

    p = f'{R.ROOT}/include/graphics.h'
    text = open(p).read()
    if 'gItemIcon_LiquidOre' not in text:
        anchor = 'extern const u32 gItemIcon_Nugget[];'
        text = text.replace(anchor, anchor + f'\n{MARK}\n'
                            'extern const u32 gItemIcon_LiquidOre[];\n'
                            'extern const u32 gItemIconPalette_LiquidOre[];', 1)
        done.append('externs')
        if not dry:
            open(p, 'w').write(text)

    p = f'{R.ROOT}/src/data/item_icon_table.h'
    text = open(p).read()
    if f'[{ITEM}]' not in text:
        # before the return-to-field arrow, which is indexed at ITEMS_COUNT and
        # so has to stay last
        anchor = '    // Return to field arrow'
        text = text.replace(anchor, f'    {MARK}\n    [{ITEM}] = '
                            '{gItemIcon_LiquidOre, gItemIconPalette_LiquidOre},\n'
                            + anchor, 1)
        done.append('icon table')
        if not dry:
            open(p, 'w').write(text)

    write_icon(dry)
    return done


# --- the flags this needs -------------------------------------------------
FLAG = 'FLAG_LITTLEROOT_SLIME_TRADED'
HIDE = 'FLAG_HIDE_GRANITE_CAVE_TRADER_STEVEN'
FLAGS = 'include/constants/flags.h'


def add_flags(dry):
    """rename FLAG_UNUSEDs, the way tools/populate.py claims its own.

    The old name stays in the comment so a re-run finds the flag it already
    took instead of walking further down the pool every time, and so the two
    tools cannot end up on the same bit: populate.py only reads lines still
    labelled "Unused Flag", and only hands back the ones carrying its mark.
    """
    p = f'{R.ROOT}/{FLAGS}'
    text = open(p).read()
    done = []
    for name in (FLAG, HIDE):
        if re.search(r'^#define ' + name + r'\s', text, re.M):
            continue
        m = re.search(r'^#define (FLAG_UNUSED_0x[0-9A-Fa-f]+)\s+'
                      r'(0x[0-9A-Fa-f]+) // Unused Flag$', text, re.M)
        if not m:
            sys.exit('no unused flags left')
        pad = ' ' * max(1, 60 - len(name))
        text = text.replace(
            m.group(0), f'#define {name}{pad}{m.group(2)} {MARK} ({m.group(1)})', 1)
        done.append(f'{name} = {m.group(2)} (was {m.group(1)})')
    if done and not dry:
        open(p, 'w').write(text)
    return done


# --- the three trades -----------------------------------------------------
def add_trades(dry):
    done = []
    p = f'{R.ROOT}/include/constants/trade.h'
    text = open(p).read()
    if TRADES[0][0] not in text:
        m = re.search(r'^#define INGAME_TRADE_MEOWTH (\d+)$', text, re.M)
        n = int(m.group(1))
        add = '\n'.join(f'#define {c} {n + 1 + k}'
                        for k, (c, _, _) in enumerate(TRADES))
        text = text.replace(m.group(0), m.group(0) + f'\n{MARK}\n' + add, 1)
        done.append(f'{len(TRADES)} trade ids from {n + 1}')
        if not dry:
            open(p, 'w').write(text)

    p = f'{R.ROOT}/src/data/trade.h'
    text = open(p).read()
    rows = ''
    for const, starter, _ in TRADES:
        rows += (
            f'    [{const}] =\n'
            f'    {{\n'
            f'        .nickname = _("{NICKNAME}"),\n'
            f'        .species = SPECIES_SLIME,\n'
            f'        .ivs = {{15, 15, 15, 15, 15, 15}},\n'
            f'        .abilityNum = 0,\n'
            f'        .otId = {OT_ID},\n'
            f'        .conditions = {{5, 5, 5, 5, 5}},\n'
            f'        .personality = {PERSONALITY},\n'
            f'        .heldItem = ITEM_NONE,\n'
            f'        .mailNum = -1,\n'
            f'        .otName = _("{OT_NAME}"),\n'
            f'        .otGender = MALE,\n'
            f'        .sheen = 10,\n'
            f'        .requestedSpecies = {starter}\n'
            f'    }},\n')
    i = text.index('static const struct InGameTrade sIngameTrades[]')
    j = text.index('\n};', i)
    # Rewrite the whole generated tail rather than only adding it when absent -
    # a row whose contents change is otherwise left as whatever the first run
    # happened to write, and the tool quietly stops meaning what it says.
    k = text.find(f'    {MARK}\n', i, j)
    if k >= 0:
        text = text[:k] + f'    {MARK}\n' + rows + text[j + 1:]
        done.append('sIngameTrades rows rewritten')
    else:
        # vanilla's last entry has no trailing comma, being last
        text = text[:j] + ',\n' + f'    {MARK}\n' + rows + text[j + 1:]
        done.append('sIngameTrades rows')
    if not dry:
        open(p, 'w').write(text)
    return done


