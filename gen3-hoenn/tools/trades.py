def add_npcs(dry):
    import json
    done = []
    p = f'{R.ROOT}/data/maps/{NAME}/scripts.inc'
    src = open(p).read()
    if SMARK in src:
        src = src[:src.index(SMARK)] + src[src.index(SMARK_END) + len(SMARK_END):]
    # before the gate block, which tools/newmaps.py cuts at its own marker and
    # rewrites; anything sitting inside that cut would be taken with it
    gate = '@ --- open hoenn: gates generated by tools/newmaps.py ---'
    body = '\n'.join(scripts()) + '\n'
    if gate in src:
        i = src.index(gate)
        src = src[:i] + body + '\n' + src[i:]
    else:
        src = src.rstrip('\n') + '\n\n' + body
    done.append('scripts')
    if not dry:
        open(p, 'w').write(src)

    p = f'{R.ROOT}/data/maps/{NAME}/map.json'
    d = json.load(open(p))
    keep = [o for o in d['object_events']
            if o['script'] not in (f'{NAME}_EventScript_SlimeTrader',
                                   f'{NAME}_EventScript_Steven')]
    for (x, y), gfx, script, look in (
            (TRADER_AT, 'OBJ_EVENT_GFX_MAN_3',
             f'{NAME}_EventScript_SlimeTrader', 'MOVEMENT_TYPE_FACE_DOWN'),
            (STEVEN_AT, 'OBJ_EVENT_GFX_STEVEN',
             f'{NAME}_EventScript_Steven', 'MOVEMENT_TYPE_FACE_DOWN')):
        keep.append({
            'graphics_id': gfx, 'x': x, 'y': y, 'elevation': 3,
            'movement_type': look, 'movement_range_x': 0, 'movement_range_y': 0,
            'trainer_type': 'TRAINER_TYPE_NONE',
            'trainer_sight_or_berry_tree_id': '0',
            'script': script, 'flag': '0'})
    d['object_events'] = keep
    done.append(f'2 object events at {TRADER_AT} and {STEVEN_AT}')
    if not dry:
        json.dump(d, open(p, 'w'), indent=2)
    return done


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()

    for what in (add_item(a.dry_run), add_flag(a.dry_run),
                 add_trades(a.dry_run), add_npcs(a.dry_run)):
        for line in what:
            print(f'  + {line}')

    if a.check:
        bad = check()
        if bad:
            sys.exit('\n'.join(bad))
        print('checks pass')


def check():
    import json, struct
    bad = []
    items = open(f'{R.ROOT}/include/constants/items.h').read()
    m = re.search(r'^#define ' + ITEM + r'\s+(\d+)$', items, re.M)
    n = re.search(r'^#define ITEMS_COUNT (\d+)$', items, re.M)
    if not m or not n:
        bad.append('item constant or ITEMS_COUNT missing')
    elif int(n.group(1)) != int(m.group(1)) + 1:
        bad.append(f'ITEMS_COUNT {n.group(1)} does not follow {ITEM} {m.group(1)}')
    tbl = open(f'{R.ROOT}/src/data/item_icon_table.h').read()
    if f'[{ITEM}]' not in tbl:
        bad.append('no icon table entry')
    if tbl.index(f'[{ITEM}]') > tbl.index('[ITEMS_COUNT]'):
        bad.append('icon entry is after the return-to-field arrow')
    for p in (ICON, PAL):
        if not os.path.exists(f'{R.ROOT}/{p}'):
            bad.append(f'{p} not written')
    if os.path.exists(f'{R.ROOT}/{ICON}'):
        from PIL import Image
        im = Image.open(f'{R.ROOT}/{ICON}')
        if im.size != (24, 24) or im.mode != 'P':
            bad.append(f'icon is {im.size} {im.mode}, want (24, 24) P')
        pal = open(f'{R.ROOT}/{PAL}').read().split('\n')
        want = [tuple(int(v) for v in l.split()) for l in pal[3:19]]
        got = im.getpalette()[:48]
        for i in range(16):
            if want[i] != tuple(got[i*3:i*3+3]):
                bad.append(f'icon palette {i} is {got[i*3:i*3+3]}, .pal says {want[i]}')
                break

    trades = open(f'{R.ROOT}/src/data/trade.h').read()
    for const, starter, _ in TRADES:
        i = trades.find(f'[{const}] =')
        if i < 0:
            bad.append(f'{const} has no row')
            continue
        blk = trades[i:trades.index('\n    },', i)]
        if f'.requestedSpecies = {starter}' not in blk:
            bad.append(f'{const} does not ask for {starter}')
        if '.species = SPECIES_SLIME' not in blk:
            bad.append(f'{const} does not offer SPECIES_SLIME')

    # the secret: no text in the generated block may name what is offered, and
    # nothing may buffer STR_VAR_2, which GetInGameTradeSpeciesInfo fills with
    # the offered species name
    src = open(f'{R.ROOT}/data/maps/{NAME}/scripts.inc').read()
    blk = src[src.index(SMARK):src.index(SMARK_END)]
    # only what the player reads. Label names are allowed to say SLIME; the
    # dialogue is not, and neither is STR_VAR_2, which
    # GetInGameTradeSpeciesInfo fills with the offered species' name.
    said = '\n'.join(re.findall(r'^\t\.string "(.*)"$', blk, re.M))
    trader = said[:said.index('Steven')] if 'Steven' in said else said
    for leak in ('STR_VAR_2', 'SLIME', 'Slime', 'slime'):
        if leak in trader:
            bad.append(f"the trader says {leak!r}, which gives it away")
    if 'FLAG_' + FLAG[5:] not in blk:
        bad.append('the trade is not flagged, so it would repeat')
    if 'MOVEMENT_TYPE' in blk:
        bad.append('movement belongs in the map, not the script block')

    # both of them stand somewhere real, and neither blocks the only way past
    d = json.load(open(f'{R.ROOT}/data/maps/{NAME}/map.json'))
    lay, maps, _ = R.solve()
    L = lay[maps['MAP_LITTLEROOT_TOWN']['layout']]
    w, h = L['width'], L['height']
    raw = struct.unpack(f'<{w*h}H',
                        open(f'{R.ROOT}/{L["blockdata_filepath"]}', 'rb').read()[:w*h*2])
    walk = [((v >> 10) & 3) == 0 for v in raw]
    ele = [(v >> 12) & 0xF for v in raw]
    solid = {(o['x'], o['y']) for o in d['object_events']}
    for x, y in (TRADER_AT, STEVEN_AT):
        if not walk[y*w + x]:
            bad.append(f'({x},{y}) is not somewhere a person can stand')
    # with every sprite treated as a wall, can the player still get everywhere?
    ok = lambda a, b: a == b or 0 in (a, b) or 15 in (a, b)
    free = [i for i in range(w*h) if walk[i] and (i % w, i // w) not in solid]
    if free:
        seen, q = {free[0]}, [free[0]]
        while q:
            i = q.pop()
            x, y = i % w, i // w
            for nx, ny in ((x+1, y), (x-1, y), (x, y+1), (x, y-1)):
                j = ny*w + nx
                if (0 <= nx < w and 0 <= ny < h and j not in seen and walk[j]
                        and (nx, ny) not in solid and ok(ele[i], ele[j])):
                    seen.add(j)
                    q.append(j)
        stranded = len(free) - len(seen)
        if stranded:
            bad.append(f'{stranded} cells of Littleroot are cut off by a sprite')
    return bad


