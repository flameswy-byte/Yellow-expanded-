def splice(path, body, before=None):
    """put a generated block in a map's scripts.inc, replacing the last one."""
    src = open(path).read()
    if SMARK in src:
        src = src[:src.index(SMARK)] + src[src.index(SMARK_END) + len(SMARK_END):]
    if before and before in src:
        i = src.index(before)
        return src[:i] + body + '\n' + src[i:]
    return src.rstrip('\n') + '\n\n' + body


def obj(x, y, gfx, script, flag='0', move='MOVEMENT_TYPE_FACE_DOWN'):
    return {'graphics_id': gfx, 'x': x, 'y': y, 'elevation': 3,
            'movement_type': move,
            'movement_range_x': 0, 'movement_range_y': 0,
            'trainer_type': 'TRAINER_TYPE_NONE',
            'trainer_sight_or_berry_tree_id': '0',
            'script': script, 'flag': flag}


def put_objects(path, mine, add, dry):
    import json
    d = json.load(open(path))
    d['object_events'] = [o for o in d['object_events']
                          if o['script'] not in mine] + add
    if not dry:
        json.dump(d, open(path, 'w'), indent=2)


