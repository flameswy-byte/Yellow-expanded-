NAME = TRADER_MAP        # the trader's map; Steven has his own now


def text(S, name, label, *lines):
    S.append(f'{name}_Text_{label}:')
    for i, l in enumerate(lines):
        S.append(f'\t.string "{l}{"$" if i == len(lines) - 1 else ""}"')
    S.append('')


